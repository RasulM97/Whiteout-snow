import { chromium } from "playwright";
import { existsSync } from "node:fs";

const origin = process.env.RAIL_ORIGIN || "http://127.0.0.1:3020/";
const executablePath = [process.env.CHROMIUM_PATH, "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe"].find((path) => path && existsSync(path));
if (!executablePath) throw new Error("No Chrome executable found");
const browser = await chromium.launch({ headless: true, executablePath });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.setDefaultTimeout(40000);
const errors = [];
page.on("pageerror", (error) => errors.push(String(error)));
await page.addInitScript(() => {
  localStorage.setItem("whiteout.settings-v2", JSON.stringify({ language: "en", quality: "low", volume: 0, muted: true, cameraShake: false, particles: false, uiScale: 1, musicEnabled: false, sfxEnabled: false, ambienceEnabled: false }));
  localStorage.setItem("whiteout.interface-tutorial.v1", JSON.stringify({ version: 1, complete: true }));
});
await page.goto(origin, { waitUntil: "domcontentloaded" });
await page.waitForFunction(() => window.__GAME_READY__ && window.__whiteoutDebug);
const report = await page.evaluate(() => {
  const d = window.__whiteoutDebug;
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  d.start(); d.setQuest(8); d.giveCredits(20000);
  const sweeper = d.build("sweeper", 0, 10);
  const purifier = d.build("purifier", 18, 10);
  const press = d.build("press", 18, 22);
  const straight = d.commitStroke([{ x: 0, z: 10 }, { x: 18, z: 10 }]);
  assert(straight.ok && straight.junctions.length === 0, `straight ${JSON.stringify(straight)}`);
  const curved = d.commitStroke([{ x: 0, z: 10 }, { x: 8, z: 16 }, { x: 18, z: 10 }]);
  assert(curved.ok && curved.reason === "reuse" && d.snapshot().credits === 20000 - straight.cost, `the same endpoints reuse the rail ${JSON.stringify(curved)}`);
  const beforeCurveCredits = d.snapshot().credits;
  const curve = d.previewStroke([{ x: 0, z: 10 }, { x: 4, z: 14 }, { x: 10, z: 16 }, { x: 18, z: 10 }]);
  assert(d.snapshot().credits === beforeCurveCredits && d.netState().edges.length === 1, "preview must not spend or build");
  d.build("sweeper", -12, 22);
  const blocked = d.commitStroke([{ x: -12, z: 22 }, { x: 18, z: 22 }]);
  assert(!blocked.ok && blocked.reason === "cargo", `raw must not feed the press ${JSON.stringify(blocked)}`);
  assert(d.snapshot().credits === beforeCurveCredits, "rejected cargo must not charge");
  d.build("heater", 4, 14);
  d.build("sweeper", 0, 14);
  d.build("purifier", 18, 14);
  const through = d.commitStroke([{ x: 0, z: 14 }, { x: 9, z: 14 }, { x: 18, z: 14 }]);
  assert(!through.ok && through.reason === "blocked", `track through a building ${JSON.stringify(through)}`);
  d.build("sweeper", 10, 0);
  d.build("purifier", 10, 20);
  const crossing = d.commitStroke([{ x: 10, z: 0 }, { x: 10, z: 20 }]);
  const cross = d.netState().junctions.find((item) => item.kind === "cross");
  assert(crossing.ok && crossing.junctions.includes("cross") && cross, `four-way ${JSON.stringify(crossing)}`);
  d.build("sweeper", 0, 8);
  const parallel = d.commitStroke([{ x: 0, z: 8 }, { x: 18, z: 8 }]);
  assert(parallel.ok && !parallel.junctions.includes("cross"), `close parallel track is not a junction ${JSON.stringify(parallel)}`);
  const merge = d.commitStroke([{ x: 10, z: 0 }, { x: 10, z: 6 }]);
  const edgesBeforeDelete = d.netState().edges.length;
  const cargoBefore = d.netState().cargo;
  const creditsBeforeDelete = d.snapshot().credits;
  const removed = d.deleteEdge(d.netState().edges[d.netState().edges.length - 1].id);
  assert(removed.ok && d.netState().edges.length === edgesBeforeDelete - 1 && d.snapshot().credits === creditsBeforeDelete && d.netState().cargo === cargoBefore, `delete keeps credits and cargo ${JSON.stringify({ removed, cargoBefore })}`);
  d.setOutput(sweeper, 40);
  d.step(1.6);
  const busyEdge = d.netState().edges[0].id;
  const busy = d.deleteEdge(busyEdge);
  assert(!busy.ok && busy.reason === "occupied" && d.netState().cargo > 0, `active capsules block deletion ${JSON.stringify(busy)}`);
  const reshaped = d.reshapeEdge(busyEdge, [{ x: 1, z: 10 }, { x: 6, z: 12 }, { x: 12, z: 9 }, { x: 17, z: 10 }]);
  assert(!reshaped.ok && reshaped.reason === "occupied", `active capsules block reshape ${JSON.stringify(reshaped)}`);
  d.step(8);
  const idle = d.netState().edges.find((edge) => !d.netState().capsules.some((capsule) => capsule.edgeId === edge.id && capsule.cargo > 0));
  const edit = idle ? d.reshapeEdge(idle.id, [{ x: 0, z: 8 }, { x: 6, z: 6 }, { x: 12, z: 8 }, { x: 18, z: 8 }]) : { ok: false, reason: "none" };
  const creditsAfterEdit = d.snapshot().credits;
  const cancelPreview = d.previewStroke([{ x: 2, z: 2 }, { x: 4, z: 4 }]);
  assert(!cancelPreview.ok && d.snapshot().credits === creditsAfterEdit, "a cancelled open stroke does not charge");
  d.save();
  const savedEdges = d.netState().edges.length;
  const savedCargo = d.netState().cargo;
  return { straight, curve: curve.reason, crossing: crossing.junctions, parallel: parallel.junctions, cross: !!cross, removed: removed.ok, busy: busy.reason, edit, savedEdges, savedCargo, span: d.buildingSpan("purifier"), credits: d.snapshot().credits, edges: d.netState().edges };
});
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForFunction(() => window.__GAME_READY__ && window.__whiteoutDebug);
const restored = await page.evaluate((saved) => {
  const d = window.__whiteoutDebug;
  d.continue();
  const state = d.netState();
  return { edges: state.edges.length, edgeList: state.edges, cargo: state.cargo, credits: d.snapshot().credits, span: d.buildingSpan("purifier"), saved };
}, report);
if (errors.length) throw new Error(errors.join("\n"));
if (!report.cross || report.busy !== "occupied" || !report.removed) throw new Error(JSON.stringify(report, null, 2));
if (restored.edges !== report.savedEdges) throw new Error(`reload lost edges ${restored.edges} vs ${report.savedEdges} ${JSON.stringify({ before: report.edges, after: restored.edgeList })}`);
if (!restored.span || restored.span.x < 1.8) throw new Error(`purifier span ${JSON.stringify(restored.span)}`);
console.log(JSON.stringify({ report, restored }, null, 2));
await browser.close();
